/*
    ==========================================
    JAVASCRIPT
    ==========================================

    JavaScript brukes til å gjøre nettsiden
    interaktiv.

    HTML = struktur
    CSS = design
    JavaScript = funksjonalitet
*/


/*
    Her lager vi en funksjon.

    En funksjon er en blokk med kode som
    kan kjøres når vi trenger den.
*/

function visMelding() {


    /*
        alert() lager en liten melding
        i nettleseren.
    */

    alert(
        "Du har trykket på knappen!"
    );

}


/*
    Funksjonen blir brukt i index.html:

    <button onclick="visMelding()">

    Når brukeren trykker på knappen,
    kjører JavaScript-funksjonen.
*/


/*
    ==========================================
    EKSTRA OPPGAVE
    ==========================================

    Elevene kan prøve å lage en ny funksjon.

    For eksempel:

    function visFilm() {

        alert("Min favorittfilm er...");

    }

    Deretter kan de koble funksjonen
    til en knapp i HTML.
*/